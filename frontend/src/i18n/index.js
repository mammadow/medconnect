const t = (key, params = {}) => {
  const dict = translations[locale.value] || translations[defaultLocale]
  const resolve = (source) => key.split('.').reduce((acc, part) => (acc ? acc[part] : undefined), source)
  let value = resolve(dict)
  if (value == null) {
    value = resolve(translations.en) ?? resolve(translations.az)
  }
  if (typeof value === 'string') {
    return value.replace(/\{(\w+)\}/g, (_, token) => {
      if (params[token] == null) return `{${token}}`
      return params[token]
    })
  }
  return value ?? key
}

const setLocale = (next) => {
  if (!translations[next]) return
  locale.value = next
  if (typeof localStorage !== 'undefined') {
    localStorage.setItem('locale', next)
  }
}

const dateLocale = computed(() => localeCodeMap[locale.value] || 'en-US')

export const useI18n = () => ({
  t,
  locale,
  setLocale,
  languages,
  dateLocale
})
